"""Build a guarded, transactional first-install artifact for Supabase SQL Editor."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "infrastructure/supabase/migrations"
OUTPUT = ROOT / "infrastructure/supabase/install.sql"

PREFLIGHT = """-- First installation only. Execute the ENTIRE file in Supabase SQL Editor.
-- No credentials, project identifiers, user accounts or test data are embedded.
-- Existing application schemas, bucket names and conflicting triggers cause an abort.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';
select pg_advisory_xact_lock(hashtext('deal-scanner:first-install'));

do $preflight$
begin
  if current_setting('server_version_num')::integer < 150000 then
    raise exception 'PostgreSQL 15 or newer is required. Nothing installed.';
  end if;
  if exists (select 1 from pg_namespace where nspname = 'deal_scanner') then
    raise exception 'Schema deal_scanner already exists. Stop: inspect migrations; do not delete it.';
  end if;
  if to_regclass('auth.users') is null or to_regprocedure('auth.uid()') is null
     or to_regclass('storage.buckets') is null or to_regclass('storage.objects') is null then
    raise exception 'Supabase Auth/Storage prerequisites are missing. Nothing installed.';
  end if;
  if (select count(*) from pg_roles where rolname in ('anon', 'authenticated', 'service_role')) <> 3 then
    raise exception 'Required Supabase roles are missing. Nothing installed.';
  end if;
  if exists (select 1 from pg_trigger where tgrelid = 'auth.users'::regclass
             and tgname = 'on_auth_user_created' and not tgisinternal) then
    raise exception 'Existing on_auth_user_created trigger is protected. Nothing installed.';
  end if;
  if exists (select 1 from storage.buckets where id in ('listing-images', 'mail-archive')
             or name in ('listing-images', 'mail-archive')) then
    raise exception 'Existing listing-images/mail-archive buckets are protected. Nothing installed.';
  end if;
  if exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects') then
    raise exception 'Existing storage policies require review before adding private app buckets. Nothing installed.';
  end if;
end;
$preflight$;
"""

POSTFLIGHT = """
-- Verify that every application table has RLS enabled before committing.
do $postflight$
begin
  if exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
             where n.nspname = 'deal_scanner' and c.relkind = 'r' and not c.relrowsecurity) then
    raise exception 'RLS verification failed. Installation rolled back.';
  end if;
end;
$postflight$;
commit;

-- Expected result: application table names, each with rls_enabled = true.
select c.relname as table_name, c.relrowsecurity as rls_enabled
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'deal_scanner' and c.relkind = 'r'
order by c.relname;
"""


def build_sql() -> str:
    chunks = ["-- GENERATED by infrastructure/scripts/build_supabase_install.py. Do not edit.\n", PREFLIGHT]
    files = sorted(MIGRATIONS.glob("*.sql"))
    if not files:
        raise ValueError("No migrations found")
    for file in files:
        source = file.read_text(encoding="utf-8")
        digest = hashlib.sha256(source.encode()).hexdigest()
        # Use explicit PL/pgSQL block terminators in the SQL Editor artifact.
        # Keep canonical migration files and their source hashes unchanged.
        source = source.replace("\nend\n$$;", "\nend;\n$$;")
        if file.name == "202607220001_initial.sql":
            # Preserve the canonical migration; first-install bundle fails closed
            # instead of replacing resources potentially owned by another app.
            trigger_drop = "drop trigger if exists on_auth_user_created on auth.users;"
            bucket_update = """on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;"""
            if source.count(trigger_drop) != 1 or source.count(bucket_update) != 1:
                raise ValueError("Initial migration changed: review first-install safety transforms")
            source = source.replace(trigger_drop, "-- Existing trigger protected by preflight.")
            source = source.replace(bucket_update, ";")
        chunks.append(f"\n-- Migration: {file.name}\n-- Source SHA256: {digest}\n{source}\n")
    return "\n".join(chunks) + POSTFLIGHT


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in artifact is out of date")
    args = parser.parse_args()
    generated = build_sql()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("install.sql is out of date; rebuild it before use")
        print("install.sql matches the guarded migration bundle")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
